-- ScreeningTogether AU - RAG knowledge schema
-- Target: PostgreSQL with pgvector
--
-- Run this file as the database owner before using the RAG upload or
-- retrieval endpoints. The application currently creates 768-dimensional
-- embeddings and explicitly casts query vectors to public.vector.
--
-- This script creates database objects only. Documents and embeddings are
-- loaded separately through the protected RAG document-ingestion endpoint.

BEGIN;

-- Keep the extension in public because the backend uses public.vector in its
-- INSERT and similarity-search SQL. Creating extensions may require the
-- database-owner role.
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;

DO $$
BEGIN
    IF to_regtype('public.vector') IS NULL THEN
        RAISE EXCEPTION
            'pgvector must be installed in the public schema because the backend uses public.vector';
    END IF;
END
$$;

CREATE SCHEMA IF NOT EXISTS rag;

CREATE TABLE IF NOT EXISTS rag.document (
    document_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name            VARCHAR(255) NOT NULL UNIQUE,
    file_hash            VARCHAR(64) NOT NULL,
    title                VARCHAR(300) NOT NULL,
    publisher            VARCHAR(200) NOT NULL,
    source_url           TEXT NOT NULL,
    published_at         DATE,
    embedding_model      VARCHAR(100) NOT NULL,
    embedding_dimensions INTEGER NOT NULL,
    pipeline_version     VARCHAR(100) NOT NULL,
    indexed_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_rag_document_file_name_not_blank
        CHECK (btrim(file_name) <> ''),
    CONSTRAINT ck_rag_document_sha256
        CHECK (file_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_rag_document_title_not_blank
        CHECK (btrim(title) <> ''),
    CONSTRAINT ck_rag_document_publisher_not_blank
        CHECK (btrim(publisher) <> ''),
    CONSTRAINT ck_rag_document_source_url
        CHECK (source_url ~* '^https?://'),
    CONSTRAINT ck_rag_document_embedding_dimensions
        CHECK (embedding_dimensions = 768),
    CONSTRAINT ck_rag_document_embedding_model_not_blank
        CHECK (btrim(embedding_model) <> ''),
    CONSTRAINT ck_rag_document_pipeline_version_not_blank
        CHECK (btrim(pipeline_version) <> '')
);

CREATE TABLE IF NOT EXISTS rag.chunk (
    chunk_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT NOT NULL,
    page_number  INTEGER NOT NULL,
    chunk_index  INTEGER NOT NULL,
    content      TEXT NOT NULL,
    embedding    public.vector(768) NOT NULL,

    CONSTRAINT fk_rag_chunk_document
        FOREIGN KEY (document_id)
        REFERENCES rag.document(document_id)
        ON DELETE CASCADE,
    CONSTRAINT uq_rag_chunk_location
        UNIQUE (document_id, page_number, chunk_index),
    CONSTRAINT ck_rag_chunk_page_number
        CHECK (page_number > 0),
    CONSTRAINT ck_rag_chunk_index
        CHECK (chunk_index >= 0),
    CONSTRAINT ck_rag_chunk_content_not_blank
        CHECK (btrim(content) <> '')
);

-- The retrieval query orders by cosine distance (<=>). HNSW avoids a full
-- table scan as the knowledge base grows.
CREATE INDEX IF NOT EXISTS idx_rag_chunk_embedding_cosine
    ON rag.chunk
    USING hnsw (embedding public.vector_cosine_ops);

COMMENT ON SCHEMA rag IS
    'Approved reference documents and vectorised chunks used by RAG.';
COMMENT ON TABLE rag.document IS
    'Source metadata and indexing configuration for each uploaded PDF.';
COMMENT ON TABLE rag.chunk IS
    'Page-level text chunks and 768-dimensional embeddings for retrieval.';
COMMENT ON COLUMN rag.document.file_hash IS
    'Lowercase SHA-256 hash of the uploaded PDF.';
COMMENT ON COLUMN rag.document.indexed_at IS
    'Time at which the document content was most recently indexed.';
COMMENT ON COLUMN rag.chunk.chunk_index IS
    'Zero-based chunk position within a PDF page.';
COMMENT ON COLUMN rag.chunk.embedding IS
    'L2-normalised embedding generated using document.embedding_model.';

-- Do not expose the knowledge schema through PostgreSQL's PUBLIC role. The
-- schema owner retains access. If the application uses a separate runtime
-- role, grant only USAGE on rag, the required table privileges, and USAGE on
-- the two identity sequences to that named role outside this repository.
REVOKE ALL PRIVILEGES ON SCHEMA rag FROM PUBLIC;
REVOKE ALL PRIVILEGES ON ALL TABLES IN SCHEMA rag FROM PUBLIC;
REVOKE ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA rag FROM PUBLIC;

COMMIT;
